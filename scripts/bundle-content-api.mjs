import fs from 'node:fs/promises';
import path from 'node:path';

const sources = [
  'supabase/functions/_shared/content-schema.mjs',
  'supabase/functions/_shared/content-handler.mjs',
  'supabase/functions/content-api/index.ts'
];
const parts = await Promise.all(sources.map(async source => {
  const code = await fs.readFile(source, 'utf8');
  return `// Source: ${source}\n${code.replace(/^import .* from ['"]\.{1,2}\/.*['"];\r?\n/gm, '')}`;
}));
const output = path.resolve('.cache', 'content-api', 'index.ts');
await fs.mkdir(path.dirname(output), { recursive: true });
await fs.writeFile(output, '// Generated by scripts/bundle-content-api.mjs. Edit original source files, then regenerate.\n' + parts.join('\n'));
console.log(`Dashboard deployment file: ${output}`);
